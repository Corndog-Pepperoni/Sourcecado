-- People and CRM store (migration slice S04). Replaces people.db.
--
-- This is the head schema of people.db at SQLite version 10. The SQLite
-- upgrade history is not replayed.
--
-- Rules (docs/engineering/postgres-port.md):
-- - Every table has user_id. Every primary key and unique key starts with
--   user_id, so two users can keep the same Apollo person, email, session id
--   or operation id.
-- - Foreign keys between these tables include user_id, so a row can never
--   point at a row of another user.
-- - Column types stay close to SQLite: TEXT -> text, INTEGER -> bigint,
--   REAL -> double precision. JSON stays text.
-- - `seq` replaces the SQLite rowid where the code orders by insertion.
-- - Text columns use collate "C". SQLite compares text byte by byte, so this
--   keeps every ORDER BY in the same order as before.
-- - people_timestamp() replaces the SQLite CURRENT_TIMESTAMP. It keeps the
--   SQLite text format, 'YYYY-MM-DD HH:MM:SS' in UTC, and the statement time.

create function people_timestamp() returns text
language sql volatile
as $$ select to_char(clock_timestamp() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS') $$;

create table people (
    user_id uuid not null references auth.users(id) on delete cascade,
    person_id text collate "C" not null,
    apollo_id text collate "C",
    first_name text collate "C",
    last_name text collate "C",
    apollo_last_name_obfuscated text collate "C",
    title text collate "C",
    company text collate "C",
    email text collate "C",
    linkedin_url text collate "C",
    phone text collate "C",
    sequence_state text collate "C",
    target text collate "C",
    handoff_who text collate "C",
    handoff_wanted text collate "C",
    handoff_happened text collate "C",
    handoff_they_want text collate "C",
    version bigint not null default 1,
    identity_revision bigint not null default 0 check (identity_revision >= 0),
    outcome text collate "C",
    deleted_at text collate "C",
    created_at text collate "C" default people_timestamp(),
    updated_at text collate "C" default people_timestamp(),
    attention_reason text collate "C",
    attention_until text collate "C",
    primary key (user_id, person_id),
    unique (user_id, apollo_id)
);

create table events (
    user_id uuid not null references auth.users(id) on delete cascade,
    seq bigint generated by default as identity,
    event_id text collate "C" not null,
    person_id text collate "C" not null,
    external_key text collate "C",
    source text collate "C" not null,
    kind text collate "C" not null,
    summary text collate "C" not null,
    payload text collate "C" not null default '{}',
    actor text collate "C" not null,
    session_id text collate "C",
    run_id text collate "C",
    tool text collate "C",
    created_at text collate "C" default people_timestamp(),
    primary key (user_id, event_id),
    unique (user_id, person_id, external_key)
);
create index events_user_person_seq on events (user_id, person_id, seq);

