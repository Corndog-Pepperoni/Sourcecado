create table crm_proposals (
    user_id uuid not null references auth.users(id) on delete cascade,
    proposal_id text collate "C" not null,
    person_id text collate "C" not null,
    target_kind text collate "C" not null check (target_kind in ('description', 'task_create', 'task_update', 'status')),
    target_id text collate "C",
    target_slot text collate "C" check (target_slot in ('general', 'detailed')),
    proposed_value text collate "C" not null,
    expected_target_version bigint not null check (expected_target_version >= 0),
    version bigint not null default 1 check (version >= 1),
    reason text collate "C" not null check (length(reason) between 1 and 500),
    source_refs text collate "C" not null,
    intent_key text collate "C" not null,
    support_source_fingerprint text collate "C" not null,
    input_revision bigint not null,
    state text collate "C" not null check (state in ('pending', 'accepted', 'dismissed')),
    resolution text collate "C",
    resolution_receipt_json text collate "C",
    change_id text collate "C",
    created_at text collate "C" not null,
    updated_at text collate "C" not null,
    primary key (user_id, proposal_id),
    unique (user_id, person_id, intent_key, support_source_fingerprint),
    check ((target_kind = 'description' and target_slot in ('general', 'detailed'))
        or (target_kind != 'description' and target_slot is null)),
    foreign key (user_id, person_id) references people (user_id, person_id),
    foreign key (user_id, change_id) references crm_changes (user_id, change_id)
);

