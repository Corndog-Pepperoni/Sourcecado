create table person_descriptions (
    user_id uuid not null references auth.users(id) on delete cascade,
    person_id text collate "C" not null,
    slot text collate "C" not null,
    text text collate "C",
    authority text collate "C" not null default 'assistant',
    source_refs text collate "C" not null default '[]',
    version bigint not null default 0,
    created_at text collate "C" default people_timestamp(),
    updated_at text collate "C" default people_timestamp(),
