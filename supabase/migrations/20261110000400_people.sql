create table person_tasks (
    user_id uuid not null references auth.users(id) on delete cascade,
    task_id text collate "C" not null,
    person_id text collate "C" not null,
    title text collate "C" not null check (length(title) between 1 and 200),
    details text collate "C" not null default '' check (length(details) <= 4000),
    due_date text collate "C" check (due_date is null or due_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
    due_timezone text collate "C",
    state text collate "C" not null default 'open' check (state in ('open', 'completed', 'cancelled')),
    origin text collate "C" not null check (origin in ('human', 'assistant')),
    protected_fields text collate "C" not null default '[]',
    source_refs text collate "C" not null default '[]',
    version bigint not null default 1 check (version >= 1),
    created_at text collate "C" not null,
    updated_at text collate "C" not null,
    completed_at text collate "C",
    check ((due_date is null) = (due_timezone is null)),
    primary key (user_id, task_id),
    foreign key (user_id, person_id) references people (user_id, person_id)
);
create index person_tasks_person_state_due on person_tasks (user_id, person_id, state, due_date);
create index person_tasks_state_due on person_tasks (user_id, state, due_date, task_id);

create table crm_changes (
    user_id uuid not null references auth.users(id) on delete cascade,
    seq bigint generated by default as identity,
    change_id text collate "C" not null,
    person_id text collate "C" not null,
    entity_type text collate "C" not null check (entity_type in (
        'task', 'description', 'attention', 'proposal', 'review', 'status',
        'artifact', 'person_details'
    )),
    entity_id text collate "C" not null,
    entity_version bigint not null check (entity_version >= 1),
    action text collate "C" not null check (action in (
        'create', 'update', 'complete', 'reopen', 'cancel', 'undo', 'accept',
        'dismiss'
    )),
    before_json text collate "C",
    after_json text collate "C" not null,
    actor text collate "C" not null check (actor in ('director', 'assistant')),
    reason text collate "C" not null,
    source_refs text collate "C" not null default '[]',
    operation_id text collate "C" not null,
    session_id text collate "C",
    run_id text collate "C",
    compensates_change_id text collate "C",
    created_at text collate "C" not null,
    primary key (user_id, change_id),
    foreign key (user_id, person_id) references people (user_id, person_id),
    foreign key (user_id, compensates_change_id) references crm_changes (user_id, change_id)
);
create index crm_changes_entity on crm_changes (user_id, entity_type, entity_id, created_at);
create index crm_changes_person_seq on crm_changes (user_id, person_id, seq);

